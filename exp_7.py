# STEP 2: Import libraries
import re
import time
from getpass import getpass
from google import genai
from google.genai import errors

# STEP 3: Configure Gemini API
API_KEY = getpass("Enter your Gemini API key: ")
client = genai.Client(api_key=API_KEY)

MODEL = "gemini-3.8-flash"
TEMPERATURE = 0.7

# ============================================================
# STEP 4: Define the initial prompt
# ============================================================

initial_prompt = """
Describe a smartwatch in no more than 60 words.

Constraints:
1. Use exactly 3 bullet points.
2. Each bullet point must start with a verb.
3. Do not use the word "smart" anywhere in your response.
"""

# ============================================================
# STEP 5: Generate response with retry
# ============================================================

def generate_with_retry(prompt):
    for attempt in range(4):
        try:
            return client.models.generate_content(
                model=MODEL,
                contents=prompt,
                config={"temperature": TEMPERATURE}
            )

        except errors.ServerError:
            if attempt == 3:
                raise

            wait_seconds = 2 ** (attempt + 1)
            print(f"Temporary server error. Retrying in {wait_seconds}s...")
            time.sleep(wait_seconds)


# ============================================================
# STEP 6: Check response constraints
# ============================================================

def check_constraints(response_text):
    # Extract bullet points beginning with -, *, or a bullet character
    bullets = re.findall(
        r"^\s*[-*•]\s+(.+?)\s*$",
        response_text,
        flags=re.MULTILINE
    )

    # Common action verbs that may begin a bullet point
    verbs = {
        "track", "tracks", "tracking",
        "display", "displays", "displaying",
        "monitor", "monitors", "monitoring",
        "measure", "measures", "measuring",
        "provide", "provides", "providing",
        "offer", "offers", "offering",
        "connect", "connects", "connecting",
        "record", "records", "recording",
        "help", "helps", "helping",
        "last", "lasts", "lasting",
        "show", "shows", "showing",
        "keep", "keeps", "keeping",
        "manage", "manages", "managing",
        "receive", "receives", "receiving",
        "count", "counts", "counting",
        "guide", "guides", "guiding"
    }

    # Check whether each bullet starts with a listed verb
    bullet_starts_with_verb = []
    for bullet in bullets:
        first_word = re.sub(
            r"^[^A-Za-z]+|[^A-Za-z]+$",
            "",
            bullet.split()[0]
        ).lower() if bullet.split() else ""

        bullet_starts_with_verb.append(first_word in verbs)

    # Check banned word as a whole word, ignoring case
    banned_word_used = bool(
        re.search(r"\bsmart\b", response_text, flags=re.IGNORECASE)
    )

    # Count words in the entire response
    word_count = len(response_text.split())

    return {
        "bullet_count": len(bullets),
        "exactly_3_bullets": len(bullets) == 3,
        "bullet_verb_results": bullet_starts_with_verb,
        "all_bullets_start_with_verb": (
            len(bullets) == 3
            and all(bullet_starts_with_verb)
        ),
        "banned_word_used": banned_word_used,
        "within_60_words": word_count <= 60,
        "word_count": word_count
    }


def print_report(report):
    print("Bullet points:", report["bullet_count"])
    print(
        "Exactly 3 bullets:",
        "PASS" if report["exactly_3_bullets"] else "FAIL"
    )
    print(
        "Each bullet starts with a verb:",
        "PASS" if report["all_bullets_start_with_verb"] else "FAIL"
    )
    print(
        "Banned word absent:",
        "PASS" if not report["banned_word_used"] else "FAIL"
    )
    print(
        "Maximum 60 words:",
        "PASS" if report["within_60_words"] else "FAIL"
    )
    print("Word count:", report["word_count"])


# ============================================================
# STEP 7: Generate and evaluate initial response
# ============================================================

try:
    initial_response = generate_with_retry(initial_prompt)
    initial_text = initial_response.text or ""

    print("\n========== INITIAL PROMPT ==========")
    print(initial_prompt)

    print("\n========== INITIAL RESPONSE ==========")
    print(initial_text or "No text returned.")

    initial_report = check_constraints(initial_text)

    print("\n========== INITIAL VIOLATION REPORT ==========")
    print_report(initial_report)

    # ========================================================
    # STEP 8: Create refined prompt
    # ========================================================

    refined_prompt = """
Describe a smartwatch in no more than 60 words.

Follow ALL these constraints:
1. Output exactly 3 bullet points, using a hyphen (-) for each bullet.
2. Begin every bullet with one of these action verbs:
   Tracks, Displays, Monitors, Measures, Provides, or Connects.
3. Never include the prohibited word that begins with "s" and ends
   with "mart", regardless of capitalization.
4. Keep the complete response under 60 words.
5. Output only the 3 bullet points. Do not add a title or explanation.

Follow this example's format, but write a different description:
- Tracks daily activity and steps.
- Displays messages and useful alerts.
- Monitors activity throughout the day.
"""

    # ========================================================
    # STEP 9: Generate and evaluate refined response
    # ========================================================

    refined_response = generate_with_retry(refined_prompt)
    refined_text = refined_response.text or ""

    print("\n========== REFINED PROMPT ==========")
    print(refined_prompt)

    print("\n========== REFINED RESPONSE ==========")
    print(refined_text or "No text returned.")

    refined_report = check_constraints(refined_text)

    print("\n========== REFINED VIOLATION REPORT ==========")
    print_report(refined_report)

    # ========================================================
    # STEP 10: Compare initial and refined outputs
    # ========================================================

    initial_passes = sum([
        initial_report["exactly_3_bullets"],
        initial_report["all_bullets_start_with_verb"],
        not initial_report["banned_word_used"],
        initial_report["within_60_words"]
    ])

    refined_passes = sum([
        refined_report["exactly_3_bullets"],
        refined_report["all_bullets_start_with_verb"],
        not refined_report["banned_word_used"],
        refined_report["within_60_words"]
    ])

    print("\n========== FINAL COMPARISON ==========")
    print(f"Initial constraints passed: {initial_passes}/4")
    print(f"Refined constraints passed: {refined_passes}/4")

    if refined_passes > initial_passes:
        print("Result: Prompt refinement improved compliance.")
    elif refined_passes == initial_passes:
        print("Result: No change in the number of constraints passed.")
    else:
        print("Result: The refined response passed fewer constraints.")

    print("""
Analysis:
The initial prompt establishes the basic requirements.
The refined prompt makes the output format more explicit,
provides allowed opening verbs, and includes a formatting example.

The checks use simple Python rules. The verb list is limited,
and the word count includes any formatting or extra text.
Review the output manually to confirm complete compliance.
""")

except errors.ClientError as e:
    print("\nGemini API request failed.")
    print("Check your API key and whether the selected model is available.")
    print("Details:", e)

except Exception as e:
    print("\nUnexpected error:", e)

